export function translate(text, isFa) {
  if (!isFa || text == null) return text
  return Object.hasOwn(fa, text) ? fa[text] : text
}

export function pathnameFor(path, isFa) {
  if (!path.startsWith('/')) return path
  const english = path.replace(/^\/fa(?=\/|\?|$)/, '') || '/'
  return isFa ? '/fa' + (english === '/' ? '/' : english) : english
}

export function isPersianPath(urlPath) {
  return /^\/fa(?:\/|$)/.test(urlPath)
}

export function alternateLocaleUrl(location, isFa) {
  return pathnameFor(location, !isFa)
}
